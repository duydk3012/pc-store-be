-- H2 fixture for the original V6 receipt tables, not a production migration.
CREATE TABLE IF NOT EXISTS goods_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100),
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id),
    received_at TIMESTAMP(6),
    received_by BIGINT REFERENCES users(id),
    status TINYINT NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by BIGINT,
    last_modified_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id BIGINT NOT NULL REFERENCES goods_receipts(id),
    purchase_order_item_id BIGINT NOT NULL REFERENCES purchase_order_items(id),
    actual_unit_cost BIGINT NOT NULL DEFAULT 0,
    quantity_received INT NOT NULL DEFAULT 0,
    quantity_accepted INT NOT NULL DEFAULT 0,
    quantity_defective INT NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by BIGINT,
    last_modified_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
